"""Settings. Secrets come from backend/.env only; nothing secret has a default."""
from functools import lru_cache
from pathlib import Path

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

BACKEND = Path(__file__).resolve().parents[2]
ROOT = BACKEND.parent


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=BACKEND / ".env", env_file_encoding="utf-8", extra="ignore")

    secret_key: str = ""            # signs session cookies; generated by scripts/init_env.py
    owner_username: str = "owner"
    owner_password_hash: str = ""   # pbkdf2 hash; set with scripts/set_password.py
    cookie_secure: bool = False      # True behind HTTPS (Cloudflare)

    storage_dir: Path = ROOT / "storage"
    database_url: str = ""

    ollama_url: str = "http://127.0.0.1:11434"
    chat_model: str = "qwen3:4b-instruct"
    embed_model: str = "bge-m3"
    vision_model: str = "qwen2.5vl:3b"
    llm_timeout_s: float = 120.0

    # ZIP limits
    max_zip_mb: int = 100
    max_files: int = 500
    max_unpacked_mb: int = 500
    max_ratio: int = 100

    max_contacts: int = 5

    # WhatsApp bridge (Node sidecar). "local": backend starts it (laptop). "external": its own container (server).
    bridge_mode: str = "local"
    bridge_url: str = "http://127.0.0.1:8200"
    bridge_secret: str = ""
    wa_session_key: str = ""
    node_exe: str = "node"
    bridge_dir: Path = ROOT / "wa-bridge"
    reply_timeout_s: float = 180.0

    @field_validator("database_url", mode="before")
    @classmethod
    def _db(cls, v):
        return v or f"sqlite:///{(ROOT / 'storage' / 'agent.db').as_posix()}"   # laptop default; server uses Postgres


@lru_cache
def get_settings() -> Settings:
    s = Settings()
    for sub in ("uploads", "extracted", "whatsapp_sessions"):
        (s.storage_dir / sub).mkdir(parents=True, exist_ok=True)
    return s
